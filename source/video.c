static uint16_t* s_top = NULL;

/* RGB565 */
#define RGB(r, g, b) ((uint16_t)(((r) >> 3) << 11 | ((g) >> 2) << 5 | ((b) >> 3)))

void video_init(void) {
	gfxInit(GSP_RGB565_OES, GSP_BGR8_OES, false);
	gfxSetDoubleBuffering(GFX_TOP, true);
	gfxSetDoubleBuffering(GFX_BOTTOM, true);
	consoleInit(GFX_BOTTOM, NULL);
}

void video_exit(void) {
	gfxExit();
}

static inline void plot(int x, int y, uint16_t c) {
	if ((unsigned)x >= TOP_WIDTH || (unsigned)y >= TOP_HEIGHT) return;
	s_top[x * TOP_HEIGHT + (TOP_HEIGHT - 1 - y)] = c;
}

void video_present(const uint16_t* pixels, int stride) {
	s_top = (uint16_t*)gfxGetFramebuffer(GFX_TOP, GFX_LEFT, NULL, NULL);
	(void)gfxGetFramebuffer(GFX_BOTTOM, GFX_LEFT, NULL, NULL);
	if (!s_top) return;
	memset(s_top, 0, TOP_WIDTH * TOP_HEIGHT * 2);
	if (!pixels || stride <= 0) return;

	/* 1x is the only mode that stays responsive inside a PC 3DS emulator. */
	int dw = GBA_WIDTH;
	int dh = GBA_HEIGHT;
	int ox = (TOP_WIDTH - dw) / 2;
	int oy = (TOP_HEIGHT - dh) / 2;
	if (g_app.scale == SCALE_FILL) {
		dw = TOP_WIDTH;
		dh = TOP_HEIGHT;
		ox = 0;
		oy = 0;
	} else if (g_app.scale == SCALE_FIT) {
		dw = 360;
		dh = 240;
		ox = (TOP_WIDTH - dw) / 2;
		oy = 0;
	}

	if (g_app.scale == SCALE_1X) {
		for (int y = 0; y < dh; y++) {
			const uint16_t* src = pixels + y * stride;
			int dy = oy + y;
			for (int x = 0; x < dw; x++) {
				s_top[(ox + x) * TOP_HEIGHT + (TOP_HEIGHT - 1 - dy)] = src[x];
			}
		}
		return;
	}

	for (int y = 0; y < dh; y++) {
		int sy = y * GBA_HEIGHT / dh;
		const uint16_t* src = pixels + sy * stride;
		int dy = oy + y;
		for (int x = 0; x < dw; x++) {
			int sx = x * GBA_WIDTH / dw;
			s_top[(ox + x) * TOP_HEIGHT + (TOP_HEIGHT - 1 - dy)] = src[sx];
		}
	}
}

void video_overlay_bar(int x, int y, int w, int h, uint16_t color) {
	if (!s_top) s_top = (uint16_t*)gfxGetFramebuffer(GFX_TOP, GFX_LEFT, NULL, NULL);
	if (!s_top) return;
	for (int yy = 0; yy < h; yy++) {
		for (int xx = 0; xx < w; xx++) plot(x + xx, y + yy, color);
	}
}

